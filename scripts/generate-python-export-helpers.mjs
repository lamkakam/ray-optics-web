import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, "..");

const apertureSourceFiles = [
  "src/python/src/rayoptics_web_utils/aperture/annular.py",
  "src/python/src/rayoptics_web_utils/aperture/offset_circular.py",
  "src/python/src/rayoptics_web_utils/aperture/offset_rotated_rectangular.py",
  "src/python/src/rayoptics_web_utils/aperture/ronchi_ruling.py",
];

const apertureHelperSource = apertureSourceFiles
  .map((filePath) => readFileSync(resolve(projectRoot, filePath), "utf8"))
  .join("\n");

const generatedHelpers = [
  {
    outputFile:
      "src/shared/lib/utils/generated/pythonExportApertureHelpers.ts",
    exportName: "pythonExportApertureHelpers",
    source: apertureHelperSource,
  },
  {
    outputFile:
      "src/shared/lib/utils/generated/pythonExportExactSpecHelpers.ts",
    exportName: "pythonExportExactSpecHelpers",
    source: readFileSync(
      resolve(
        projectRoot,
        "src/python/src/rayoptics_web_utils/optical_specs.py",
      ),
      "utf8",
    ),
  },
];

for (const { outputFile, exportName, source } of generatedHelpers) {
  const outputPath = resolve(projectRoot, outputFile);
  const output = `// This file is generated by scripts/generate-python-export-helpers.mjs.
// Do not edit by hand.

export const ${exportName} = ${JSON.stringify(source)};
`;

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, output);
}
